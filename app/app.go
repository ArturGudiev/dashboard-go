package app

import (
	"context"

	"arturgudiev/dashboard/ent"
	"arturgudiev/dashboard/services"
)

// App holds all application dependencies
type App struct {
	Client             *ent.Client
	TaskService        *services.TaskService
	ProblemService     *services.ProblemService
	ContainerService   *services.ContainerService
	CLIService         *services.CLIService
	ProblemsRepository *services.ProblemsRepository
	ctx                context.Context // Default context for CLI operations
}

// NewApp creates a new App instance with all dependencies initialized using Wire
// This function is generated by Wire - do not edit manually
// To regenerate, run: wire gen ./app
func NewApp() (*App, error) {
	return InitializeApp()
}

// Close closes all resources
func (a *App) Close() error {
	return a.Client.Close()
}

// FinishTaskRecursively finishes all open descendant tasks using default context
func (a *App) FinishTaskRecursively(task *ent.Task) error {
	return a.TaskService.FinishTaskRecursively(a.ctx, task)
}
